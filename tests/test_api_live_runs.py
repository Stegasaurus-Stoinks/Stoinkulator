def client_at(db: Path, now: datetime) -> TestClient:
    """A client whose app clock is fixed at `now`."""
    app = create_app(str(db), NO_ENV, now=lambda: now)
    return TestClient(app, base_url="http://127.0.0.1:8750")


def live_meta(directory: str = "", last_bar: datetime | None = None):
    data = DataMeta(source="live", directory=directory, symbols=SYMBOLS, first_bar=T0,
                    last_bar=last_bar)
    return replace(meta("paper-live"), config={}, data=data)


def live_run(store: SqliteStore, clock: Clock, *, started: datetime, touched: datetime | None,
             status: str | None = None, reason: str | None = None, directory: str = "",
             bars: list[StoredBar] | None = None, counts: bool = True) -> int:
    """One live run written as the live writer will: positions, bars, counts, heartbeat."""
    clock.now = started
    run_id = store.begin_run(live_meta(directory))
    store.write_algos(run_id, algos())
    led = live_ledger()
    store.write_results(run_id, order_events=led.orders, fills=led.fills,
                        round_trips=led.round_trips, equity=led.equity_points)
    store.write_bars(run_id, bars if bars is not None else [
        StoredBar("AAPL", minute(4), 1.0, 1.0, 1.0, 103.0, 10.0),
        StoredBar("AAPL", minute(5), 1.0, 1.0, 1.0, 104.5, 10.0),
        StoredBar("MSFT", minute(5), 1.0, 1.0, 1.0, 49.25, 10.0)])
    if counts:
        store.set_counts(run_id, COUNTS)
    if touched is not None:
        clock.now = touched
        store.touch(run_id)
    if status is not None:
        store.end_run(run_id, status, reason)  # type: ignore[arg-type]
    return run_id


def backtest_database(tmp_path: Path) -> Path:
    """Two backtests (one finished, one left running) over a bars file; fixed times."""
    directory = tmp_path / "bars-data"
    directory.mkdir()
    write_bars(directory, "AAPL", [datetime(2024, 1, 2)])
    sha, size = file_fingerprint(offline_data_path(directory, "AAPL"))
    data = DataMeta(source="offline", directory=str(directory), symbols=SYMBOLS, first_bar=T0,
                    last_bar=T0 + timedelta(minutes=5), files=(("AAPL", sha, size),))
    path = tmp_path / "backtest.db"
    times = iter(START + timedelta(seconds=n) for n in range(10))
    with SqliteStore(path, clock=lambda: next(times)) as store:
        run_id = store.begin_run(replace(meta(), data=data))
        store.write_algos(run_id, algos())
        write_all(store, run_id, build_ledger())
        store.end_run(run_id, "completed")
        store.begin_run(replace(meta(), data=data))  # never ended
    return path


def backtest_responses(db: Path) -> dict[str, str]:
    """The text of every route's response for the backtests of `backtest_database`."""
    client = make_client(db)
    window = {"symbol": "AAPL", "start": "2024-01-02T09:30:00", "end": "2024-01-02T09:33:00"}
    routes = {
        "runs": ("/api/runs", {}),
        "detail_completed": ("/api/runs/1", {}),
        "detail_running": ("/api/runs/2", {}),
        "bars_window": ("/api/runs/1/bars", window),
        "bars_default_day": ("/api/runs/1/bars", {"symbol": "AAPL"}),
        "bars_unknown_symbol": ("/api/runs/1/bars", {"symbol": "TSLA"}),
        "bars_running_run": ("/api/runs/2/bars", {"symbol": "AAPL"}),
    }
    out: dict[str, str] = {}
    for name, (url, params) in routes.items():
        response = client.get(url, params=params)
        out[name] = f"{response.status_code} {response.text}"
    return out


