def test_the_clock_is_read_once_per_request(db):
    clock = Clock()
    with SqliteStore(db, clock=clock) as store:
        live_run(store, clock, started=START, touched=START)
        live_run(store, clock, started=START, touched=START)
    calls: list[int] = []

    def counting() -> datetime:
        calls.append(1)
        return START

    client = TestClient(create_app(str(db), NO_ENV, now=counting),
                        base_url="http://127.0.0.1:8750")
    for url in ("/api/runs", "/api/runs/1", "/api/health"):
        calls.clear()
        assert client.get(url).status_code == 200
        assert len(calls) == 1, url


