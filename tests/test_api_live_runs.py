def test_health_running_vs_stale(db):
    clock = Clock()
    with SqliteStore(db, clock=clock) as store:
        live_run(store, clock, started=START, touched=START)
        done = live_run(store, clock, started=START, touched=START, status="completed",
                        reason="session_end")
    assert done == 2
    soon = client_at(db, START + timedelta(seconds=30)).get("/api/health").json()
    assert soon["live_state"] == "running"
    assert soon["running_runs"] == [1] and soon["stale_runs"] == []
    assert soon["incomplete_runs"] == [1] and soon["run_count"] == 2
    late = client_at(db, START + STALE_AFTER + timedelta(seconds=1)).get("/api/health").json()
    assert late["live_state"] == "stale"
    assert late["running_runs"] == [] and late["stale_runs"] == [1]
    assert late["incomplete_runs"] == [1]  # still marked running, as before
    # one running run among stale ones: the database is running
    with SqliteStore(db, clock=clock) as store:
        live_run(store, clock, started=START, touched=START + STALE_AFTER)
    mixed = client_at(db, START + STALE_AFTER + timedelta(seconds=1)).get("/api/health").json()
    assert mixed["live_state"] == "running"
    assert mixed["running_runs"] == [3] and mixed["stale_runs"] == [1]


