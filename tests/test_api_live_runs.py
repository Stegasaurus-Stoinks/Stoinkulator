@pytest.mark.parametrize("version", [1, 2])
def test_old_databases_work_through_every_route(tmp_path, version):
    src = backtest_database(tmp_path)
    expected = backtest_responses(src)
    old = tmp_path / f"v{version}.db"
    make_old_file(src, old, version)
    # run 2 is a never-ended backtest: it is copied too
    assert backtest_responses(old) == expected
    # an old file can hold a run of a live kind (the kind is free text): no live-only
    # tables, columns or counts, yet every route answers
    con = sqlite3.connect(old)
    con.execute("UPDATE runs SET kind='paper-live' WHERE id=2")
    con.commit()
    con.close()
    client = client_at(old, START + timedelta(days=1))
    runs = client.get("/api/runs").json()["runs"]
