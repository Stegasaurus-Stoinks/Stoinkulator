"""The market calendar: a hand-written table of 2024 to 2028, the rules, the offline data.

The tables below are written from the exchange's published holiday pattern, not
generated by the code under test.
"""
from __future__ import annotations

import json
from datetime import date, datetime, timedelta
from pathlib import Path

import pandas as pd
import pytest

from MainStoinker.engine import market_calendar as mc
from MainStoinker.engine.market_calendar import (
    close_minute,
    easter,
    is_half_day,
    is_trading_day,
    load_overrides,
    next_trading_day,
    previous_trading_day,
    session,
    trading_days,
)

D = date.fromisoformat

# Full closures on weekdays, by year (a Saturday/Sunday holiday is shown where it is observed).
HOLIDAYS = {
    2024: ["2024-01-01", "2024-01-15", "2024-02-19", "2024-03-29", "2024-05-27", "2024-06-19",
           "2024-07-04", "2024-09-02", "2024-11-28", "2024-12-25"],
    # 2025-01-01 Wed; Juneteenth Thu; July 4 Fri; Christmas Thu (2025-01-09 is an override)
    2025: ["2025-01-01", "2025-01-20", "2025-02-17", "2025-04-18", "2025-05-26", "2025-06-19",
           "2025-07-04", "2025-09-01", "2025-11-27", "2025-12-25"],
    # Juneteenth Fri; July 4 Sat -> Fri 3 July; Christmas Fri
    2026: ["2026-01-01", "2026-01-19", "2026-02-16", "2026-04-03", "2026-05-25", "2026-06-19",
           "2026-07-03", "2026-09-07", "2026-11-26", "2026-12-25"],
    # Juneteenth Sat -> Fri 18 June; July 4 Sun -> Mon 5 July; Christmas Sat -> Fri 24 Dec
    2027: ["2027-01-01", "2027-01-18", "2027-02-15", "2027-03-26", "2027-05-31", "2027-06-18",
           "2027-07-05", "2027-09-06", "2027-11-25", "2027-12-24"],
    # 2028-01-01 is a Saturday: NOT observed on Fri 2027-12-31; Juneteenth Mon; July 4 Tue
    2028: ["2028-01-17", "2028-02-21", "2028-04-14", "2028-05-29", "2028-06-19",
           "2028-07-04", "2028-09-04", "2028-11-23", "2028-12-25"],
}
EARLY_CLOSES = {
    2024: ["2024-07-03", "2024-11-29", "2024-12-24"],
    2025: ["2025-07-03", "2025-11-28", "2025-12-24"],
    2026: ["2026-11-27", "2026-12-24"],  # 3 July 2026 is the observed holiday, not an early close
    2027: ["2027-11-26"],  # Christmas Eve 2027 is the observed Christmas holiday
    2028: ["2028-07-03", "2028-11-24"],  # Christmas Eve 2028 is a Sunday
}


def every_day(year: int) -> list[date]:
    return [d for d in (date(year, 1, 1) + timedelta(n) for n in range(366)) if d.year == year]


@pytest.mark.parametrize("year", sorted(HOLIDAYS))
def test_closed_weekdays_are_exactly_the_published_holidays(year):
    expected = {D(x) for x in HOLIDAYS[year]}
    if year == 2025:
        expected.add(D("2025-01-09"))  # national day of mourning (override)
    found = {d for d in every_day(year) if d.weekday() < 5 and not is_trading_day(d)}
    assert found == expected
    assert not any(is_trading_day(d) for d in every_day(year) if d.weekday() >= 5)


@pytest.mark.parametrize("year", sorted(EARLY_CLOSES))
def test_early_closes_are_exactly_the_published_ones(year):
    found = {d for d in every_day(year) if is_half_day(d)}
    assert found == {D(x) for x in EARLY_CLOSES[year]}
    for x in EARLY_CLOSES[year]:
        assert close_minute(D(x)) == 13 * 60 and session(D(x)).open_minute == 9 * 60 + 30


def test_full_days_close_at_16():
    assert close_minute(D("2024-08-19")) == 16 * 60 and not is_half_day(D("2024-08-19"))


def test_weekends_and_holidays_have_no_session():
    assert session(D("2024-08-17")) is None and session(D("2024-12-25")) is None
    assert not is_half_day(D("2024-12-25"))
    with pytest.raises(ValueError, match="not a trading day"):
        close_minute(D("2024-12-25"))


def test_new_years_day_on_a_saturday_is_not_observed_on_the_friday():
    assert D("2022-01-01").weekday() == 5
    assert is_trading_day(D("2021-12-31")) and not is_trading_day(D("2022-01-01"))
    # on a Sunday it moves to Monday
    assert D("2023-01-01").weekday() == 6
    assert not is_trading_day(D("2023-01-02")) and is_trading_day(D("2022-12-30"))


def test_saturday_and_sunday_holidays_are_observed_on_friday_and_monday():
    # Christmas 2021 Saturday -> Friday 24th; Independence Day 2021 Sunday -> Monday 5th
    assert not is_trading_day(D("2021-12-24")) and not is_trading_day(D("2021-07-05"))
    assert is_trading_day(D("2021-12-23"))


def test_juneteenth_only_from_2022():
    assert is_trading_day(D("2021-06-18"))
    assert not is_trading_day(D("2022-06-20"))  # 19 June 2022 is a Sunday


def test_one_off_closure_in_the_override_table():
    assert D("2025-01-09").weekday() == 3
    assert session(D("2025-01-09")) is None
    assert D("2025-01-09") in mc.OVERRIDES


def test_caller_overrides_win():
    extra = {D("2024-08-19"): None, D("2024-08-20"): 12 * 60, D("2025-01-09"): mc.FULL_CLOSE_MINUTE}
    assert not is_trading_day(D("2024-08-19"), extra)
    assert close_minute(D("2024-08-20"), extra) == 720 and is_half_day(D("2024-08-20"), extra)
    assert is_trading_day(D("2025-01-09"), extra)
    assert is_trading_day(D("2024-08-19"))  # nothing global changed


def test_load_overrides_reads_json_and_checks_it(tmp_path: Path):
    path = tmp_path / "o.json"
    path.write_text(json.dumps({"2026-05-01": None, "2026-05-04": "12:00"}))
    assert load_overrides(path) == {D("2026-05-01"): None, D("2026-05-04"): 720}
    for bad in ({"2026-5-1": None}, {"2026-05-01": "noon"}, {"2026-05-01": "17:00"}, [1]):
        path.write_text(json.dumps(bad))
        with pytest.raises(ValueError):
            load_overrides(path)


@pytest.mark.parametrize(
    "year, expected",
    [(2000, "2000-04-23"), (2008, "2008-03-23"), (2019, "2019-04-21"), (2024, "2024-03-31"),
     (2025, "2025-04-20"), (2026, "2026-04-05"), (2027, "2027-03-28"), (2028, "2028-04-16"),
     (2038, "2038-04-25")],
)
def test_easter(year, expected):
    assert easter(year) == D(expected)


def test_neighbours_and_ranges_skip_closed_days():
    assert previous_trading_day(D("2024-09-03")) == D("2024-08-30")  # Labor Day weekend
    assert next_trading_day(D("2024-08-30")) == D("2024-09-03")
    assert previous_trading_day(D("2024-12-26")) == D("2024-12-24")
    assert next_trading_day(D("2024-12-24")) == D("2024-12-26")
    assert previous_trading_day(D("2022-01-03")) == D("2021-12-31")
    assert list(trading_days(D("2024-11-25"), D("2024-12-02"))) == [
        D("2024-11-25"), D("2024-11-26"), D("2024-11-27"), D("2024-11-29"), D("2024-12-02")]
    assert list(trading_days(D("2024-12-02"), D("2024-11-25"))) == []


def test_a_datetime_is_refused():
    with pytest.raises(TypeError):
        session(datetime(2024, 8, 19, 10, 0))  # type: ignore[arg-type]


def test_committed_offline_data_has_no_holiday_and_no_half_day():
    root = Path(__file__).resolve().parent.parent / "OfflineData"
    files = sorted(root.glob("_*_offlinedata_"))
    assert files
    for file in files:
        days = pd.read_csv(file, usecols=["date"], parse_dates=["date"])["date"].dt.date.unique()
        assert len(days) > 0
        for day in days:
            assert is_trading_day(day) and not is_half_day(day), (file.name, day)
